"""Serialization format comparison (local measurement).

Measures OTLP Proto vs JSON serialization overhead on a single machine.
This is a local CPU benchmark, not a Kafka or pipeline benchmark.
Results will vary by hardware but the relative difference between
Proto and JSON is consistent with industry observations (5-7x faster,
~50% smaller). See Bindplane [^8] and Confluent [^9] for production data.
"""

import json
import os
import time
import uuid
import random
from datetime import datetime, timezone
from pathlib import Path

from opentelemetry.proto.trace.v1.trace_pb2 import TracesData, ResourceSpans, ScopeSpans, Span
from opentelemetry.proto.common.v1.common_pb2 import AnyValue, KeyValue
from opentelemetry.proto.resource.v1.resource_pb2 import Resource
from google.protobuf.json_format import MessageToJson, Parse

random.seed(42)

NUM_SPANS = 10_000
# Defaults to 100 for stable numbers. Lower it for a quick run, e.g.
#   NUM_ITERATIONS=10 python bench_serialization.py
# and raise it for more accurate timings.
NUM_ITERATIONS = int(os.environ.get("NUM_ITERATIONS", "100"))
WARMUP_ITERATIONS = 1


def _tick(i: int) -> None:
    """Print a progress dot so a long run visibly shows it is alive."""
    if i % max(1, NUM_ITERATIONS // 20) == 0:
        print(".", end="", flush=True)


def _generate_span_proto(index: int) -> Span:
    trace_id = uuid.uuid4().bytes
    span_id = random.randbytes(8)
    return Span(
        trace_id=trace_id,
        span_id=span_id,
        name=f"operation-{index}",
        kind=Span.SPAN_KIND_SERVER,
        start_time_unix_nano=int(time.time() * 1e9),
        end_time_unix_nano=int(time.time() * 1e9) + random.randint(1000000, 50000000),
        attributes=[
            KeyValue(key="service.name", value=AnyValue(string_value="bench-serialization")),
            KeyValue(key="http.method", value=AnyValue(string_value=random.choice(["GET", "POST", "PUT"]))),
            KeyValue(key="http.status_code", value=AnyValue(int_value=random.choice([200, 201, 400, 500]))),
            KeyValue(key="item.index", value=AnyValue(int_value=index)),
        ],
    )


def _build_traces_data(num_spans: int) -> TracesData:
    spans = [_generate_span_proto(i) for i in range(num_spans)]
    scope_spans = ScopeSpans(spans=spans)
    resource_spans = ResourceSpans(
        resource=Resource(attributes=[
            KeyValue(key="service.name", value=AnyValue(string_value="bench-serialization")),
        ]),
        scope_spans=[scope_spans],
    )
    return TracesData(resource_spans=[resource_spans])


def _save_results(results: dict) -> tuple[str, str]:
    output_dir = Path(__file__).parent / "results"
    output_dir.mkdir(exist_ok=True)
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    json_path = output_dir / f"results-{timestamp}.json"
    md_path = output_dir / f"results-{timestamp}.md"

    with open(json_path, "w") as f:
        json.dump(results, f, indent=2, default=str)

    lines = [
        "# Chapter 4: Serialization Format Comparison",
        f"\n**Date**: {results['timestamp']}",
        f"**Platform**: {results.get('platform', 'local')}",
        "",
        "| Format | Size (bytes) | Serialize (ms) | Deserialize (ms) |",
        "|---|---|---|---|",
    ]
    for fmt in results["formats"]:
        lines.append(
            f"| {fmt['name']} | {fmt['size_bytes']:,} "
            f"| {fmt['serialize_ms']:.2f} | {fmt['deserialize_ms']:.2f} |"
        )
    lines.extend([
        "",
        f"> Proto is **{results['speed_ratio']:.1f}x** faster and "
        f"**{results['size_ratio']:.1f}x** smaller than JSON",
        f">",
        f"> {NUM_SPANS:,} spans, {NUM_ITERATIONS} iterations, {WARMUP_ITERATIONS} warmup",
        "",
        "---",
        "*Generated by chapter-04 serialization exercise*",
    ])
    with open(md_path, "w") as f:
        f.write("\n".join(lines))

    return str(json_path), str(md_path)


def run() -> dict:
    print(f"[serialization] Generating {NUM_SPANS:,} spans for comparison...")
    traces_data = _build_traces_data(NUM_SPANS)

    # -- Warmup --
    print(f"[serialization] Warming up ({WARMUP_ITERATIONS} iteration)...")
    for _ in range(WARMUP_ITERATIONS):
        traces_data.SerializeToString()
        MessageToJson(traces_data)

    # -- Proto serialization --
    print("[serialization] Benchmarking Proto serialization...")
    proto_serialize_times = []
    proto_deserialize_times = []

    for i in range(NUM_ITERATIONS):
        _tick(i)
        start = time.perf_counter()
        proto_bytes = traces_data.SerializeToString()
        proto_serialize_times.append(time.perf_counter() - start)
    print()

    proto_size = len(proto_bytes)

    for i in range(NUM_ITERATIONS):
        _tick(i)
        start = time.perf_counter()
        parsed = TracesData()
        parsed.ParseFromString(proto_bytes)
        proto_deserialize_times.append(time.perf_counter() - start)
    print()

    # -- JSON serialization --
    print("[serialization] Benchmarking JSON serialization...")
    json_serialize_times = []
    json_deserialize_times = []

    json_str = MessageToJson(traces_data)
    json_size = len(json_str.encode("utf-8"))

    for i in range(NUM_ITERATIONS):
        _tick(i)
        start = time.perf_counter()
        json_out = MessageToJson(traces_data)
        json_serialize_times.append(time.perf_counter() - start)
    print()

    for i in range(NUM_ITERATIONS):
        _tick(i)
        start = time.perf_counter()
        Parse(json_out, TracesData())
        json_deserialize_times.append(time.perf_counter() - start)
    print()

    # -- Results --
    avg_proto_ser = sum(proto_serialize_times) / len(proto_serialize_times) * 1000
    avg_proto_deser = sum(proto_deserialize_times) / len(proto_deserialize_times) * 1000
    avg_json_ser = sum(json_serialize_times) / len(json_serialize_times) * 1000
    avg_json_deser = sum(json_deserialize_times) / len(json_deserialize_times) * 1000

    speed_ratio = avg_json_ser / avg_proto_ser if avg_proto_ser > 0 else 0
    size_ratio = json_size / proto_size if proto_size > 0 else 0

    result = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "formats": [
            {
                "name": "Proto",
                "size_bytes": proto_size,
                "serialize_ms": avg_proto_ser,
                "deserialize_ms": avg_proto_deser,
            },
            {
                "name": "JSON",
                "size_bytes": json_size,
                "serialize_ms": avg_json_ser,
                "deserialize_ms": avg_json_deser,
            },
        ],
        "speed_ratio": speed_ratio,
        "size_ratio": size_ratio,
        "num_spans": NUM_SPANS,
        "num_iterations": NUM_ITERATIONS,
    }

    print(f"[serialization] Proto: {proto_size:,} bytes, {avg_proto_ser:.2f}ms serialize")
    print(f"[serialization] JSON:  {json_size:,} bytes, {avg_json_ser:.2f}ms serialize")
    print(f"[serialization] Proto is {speed_ratio:.1f}x faster, {size_ratio:.1f}x smaller")

    json_path, md_path = _save_results(result)
    print(f"[serialization] Results saved: {json_path}, {md_path}")

    return result


if __name__ == "__main__":
    run()
